-- V1__baseline.sql
--
-- The schema as Hibernate's ddl-auto built it, captured so that Flyway can own it
-- from here on.
--
-- THIS MIGRATION NEVER RUNS ON AN EXISTING DATABASE. With baseline-on-migrate
-- enabled, Flyway finds a non-empty schema with no history table, writes a
-- baseline row at version 1, and treats this file as already applied. It runs
-- only on a database created from empty. That is exactly what a baseline is for,
-- and it is also the trap: anything put in THIS file will never reach the
-- databases that already exist. Reference data therefore belongs in V2 or later,
-- never here.
--
-- Generated from pg_dump --schema-only of the live database on 2026-09-26, then
-- cleaned:
--   * \restrict and \unrestrict removed - they are psql meta-commands and Flyway
--     cannot execute them, so leaving them in fails the migration outright.
--   * The SET/set_config preamble removed. It set search_path to '', which would
--     have applied to everything Flyway ran afterwards in the same session.
--   * OWNER TO statements removed, so this applies as whatever role connects
--     rather than requiring a role named postgres to exist.
--
-- CHECK constraints are inline in each CREATE TABLE, including the 74 enum guards.
-- Several of those no longer match the Java enums; V2 corrects that.

--
